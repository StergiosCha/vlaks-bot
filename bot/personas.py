def build_context(kb, user_msg: str, chunks: list[dict], events: list) -> str:
    parts = ["=== ΤΟ ΣΠΙΤΙ ===\n" + kb.house_facts(),
             "=== ΕΥΡΕΤΗΡΙΟ ΣΕΛΙΔΩΝ (slug | τίτλος | τι έχει | url) ===\n" + kb.pages_index(),
             "=== ΕΥΡΕΤΗΡΙΟ ΓΕΓΟΝΟΤΩΝ (anchor | ημερομηνία | τίτλος) ===\n" + kb.events_index()]
    if events:
        lines = []
        for e in events[:6]:
            lines.append(
                f"- {e.anchor} | {e.date_text} | {e.title} | {e.badge or '—'} | {e.venue}"
                + (" | ΜΑΤΑΙΩΘΗΚΕ" if e.cancelled else "")
                + f"\n  Ανακοίνωση: {e.announcement[:400]}\n  Πηγές: {e.sources[:300]}"
            )
        parts.append("=== ΣΧΕΤΙΚΑ ΓΕΓΟΝΟΤΑ (αναλυτικά) ===\n" + "\n".join(lines))
    if chunks:
        parts.append("=== ΑΠΟΣΠΑΣΜΑΤΑ ΑΠΟ ΤΟ SITE ΚΑΙ ΤΟ ΑΡΧΕΙΟ ===\n" + "\n\n".join(
            f"[{c['type']}] {c['title']} — {c['url']}\n{c['text'][:1100]}" for c in chunks))
    greek = sum(1 for ch in user_msg if "Ͱ" <= ch <= "Ͽ" or "ἀ" <= ch <= "῿")
    parts.append(f"(Εικασία γλώσσας επισκέπτη: {'el' if greek >= max(2, len(user_msg) * 0.2) else 'en'})")
    return "\n\n".join(parts)


def schema_reminder() -> str:
    return "Επίστρεψε μόνο JSON αυτού του σχήματος:\n" + json.dumps(REPLY_SCHEMA, ensure_ascii=False)
